def _run(samples, th, ny, np_):
    head, gaze, gb = HeadDetector(ny, np_, th), GazeDetector(th), EventBuilder.for_gaze(th)
    blocks = getattr(head, "block_gaze", None) or head.blocks_gaze      
    states, events = [], []
    for s in samples:
        head.update(s)
        tr, ep = gaze.update(s, block=blocks(), head_score=head.last_score)
        states += [t.new for t in tr]
        events += gb.update(s, tr, ep)
    return states, events


def _frames(rows):
    return [FrameSample(ts=t, frame_idx=i, face_count=1, confidence=1.0, head_yaw=hy, head_pitch=hp,
                        head_roll=0.0, gaze_yaw=gy, gaze_pitch=gp) for i, (t, hy, hp, gy, gp) in enumerate(rows)]


def test_strong_look_with_head_drifted_down_is_detected():
    s = _frames(K_ROWS)
    before = replace(TH, head_block_ratio=0.75, head_guard_gain=0.0)     
    st_old, _ = _run(s, before, -5.55, 0.50)
    assert State.DEVIATING not in st_old                                 
    st, ev = _run(s, TH, -5.55, 0.50)
    assert State.DEVIATING in st
    assert [(e.source, e.direction) for e in ev] == [("gaze", "yaw-")]
    assert ev[0].peak > 2.5


def _tilted(head_pitch, gaze_yaw, secs=2.0):
    b = ScenarioBuilder(fps=10, noise_deg=0.0).steady(1.0)
    b._emit(secs, head=(0.0, head_pitch, 0.0), gaze=(gaze_yaw, 0.0))
    return b._emit(1.5, head=(0.0, head_pitch, 0.0), gaze=(0.0, 0.0)).build()


def test_guard_ignores_weak_gaze_when_head_is_near_its_threshold():
    st, _ = _run(_tilted(13.5, 0.072), TH, 0.0, 0.0)       
    assert State.DEVIATING not in st


def test_guard_lets_strong_gaze_through_when_head_is_near_its_threshold():
    st, ev = _run(_tilted(13.5, 0.15), TH, 0.0, 0.0)      
    assert State.DEVIATING in st and len(ev) == 1


def test_gaze_is_ignored_once_the_head_itself_deviates():
    st, ev = _run(_tilted(16.5, 0.20), TH, 0.0, 0.0)       
    assert State.DEVIATING not in st and ev == []